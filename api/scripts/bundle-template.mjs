// Bundles `vault-template/` into the Worker: walks the folder and writes
// `api/src/template.generated.ts`, the list of `{ path, content }` that
// `POST /vault` copies into a user's Drive. Runs as `prebuild`; the output
// is committed too, so lint, typecheck and tests work without running it.
// A stale committed copy is only a diff away: the next build rewrites it.
//
// Plain `.mjs` on purpose: it runs on the Node version CI uses without a
// TypeScript loader, and it needs no `@types/node` (the repo has none).
// Every Node API is imported, never used as a global, so ESLint's
// `no-undef` is satisfied without a Node globals config.
//
// Usage: node api/scripts/bundle-template.mjs

import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join, relative, sep } from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import { TextDecoder } from 'node:util';

const apiDir = dirname(dirname(fileURLToPath(import.meta.url)));
const templateDir = join(apiDir, '..', 'vault-template');
const outFile = join(apiDir, 'src', 'template.generated.ts');

// `vault-template/README.md` describes the folder to readers of this
// repository; it is not part of a user's vault, so it is not bundled.
const SKIPPED = new Set(['README.md']);

/** Every file under `dir`, as paths relative to `templateDir` with `/`. */
async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await walk(full)));
    } else if (entry.isFile()) {
      files.push(relative(templateDir, full).split(sep).join('/'));
    }
  }
  return files;
}

const utf8 = new TextDecoder('utf-8', { fatal: true });

/** The file's text with LF line endings, or `null` when it is not text. */
function asText(bytes) {
  if (bytes.includes(0)) return null;
  try {
    return utf8.decode(bytes).replace(/\r\n/g, '\n');
  } catch {
    // Not valid UTF-8, so not a text file; the caller reports and skips it.
    return null;
  }
}

/** A template literal holding `text` verbatim. */
function literal(text) {
  const escaped = text
    .replace(/\\/g, '\\\\')
    .replace(/`/g, '\\`')
    .replace(/\$\{/g, '\\${');
  return `\`${escaped}\``;
}

const paths = (await walk(templateDir))
  .filter((path) => !SKIPPED.has(path))
  .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));

const entries = [];
for (const path of paths) {
  const content = asText(await readFile(join(templateDir, path)));
  if (content === null) {
    process.stderr.write(`bundle-template: skipping non-text file ${path}\n`);
    continue;
  }
  entries.push(
    `  {\n    path: '${path}',\n    content: ${literal(content)},\n  },\n`,
  );
}

const output = `// Generated by api/scripts/bundle-template.mjs from vault-template/.
// Do not edit: change vault-template/ and run \`pnpm -C api build\`.

export interface TemplateFile {
  /** Relative to the vault root, \`/\`-separated. */
  path: string;
  /** UTF-8 text; empty for \`.gitkeep\` (a folder with nothing in it yet). */
  content: string;
}

/** Every file of the vault template, sorted by path. */
export const TEMPLATE_FILES: readonly TemplateFile[] = [
${entries.join('')}];
`;

await writeFile(outFile, output);
process.stdout.write(
  `bundle-template: wrote ${entries.length} files to src/template.generated.ts\n`,
);
