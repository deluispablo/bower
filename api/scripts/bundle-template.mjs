// Bundles `api/template/` into the Worker: writes `api/src/template.generated.ts`, the list of
// `{ path, content }` that `POST /vault` copies into a new Bower folder. Adapted from the original
// app's `api/scripts/bundle-template.mjs`. `--check` writes nothing and fails when the committed
// file is not what the template would generate (run by the `template:check` test).
//
// Usage: node api/scripts/bundle-template.mjs [--check]

import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join, relative, sep } from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const apiDir = dirname(dirname(fileURLToPath(import.meta.url)));
const templateDir = join(apiDir, 'template');
const outFile = join(apiDir, 'src', 'template.generated.ts');

async function walk(dir) {
  const files = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(full)));
    else if (entry.isFile()) files.push(relative(templateDir, full).split(sep).join('/'));
  }
  return files;
}

const literal = (text) => `\`${text.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${')}\``;

const paths = (await walk(templateDir)).sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
const entries = [];
for (const path of paths) {
  const content = (await readFile(join(templateDir, path), 'utf8')).replace(/\r\n/g, '\n');
  entries.push(`  {\n    path: '${path}',\n    content: ${literal(content)},\n  },\n`);
}

const output = `// Generated by api/scripts/bundle-template.mjs from api/template/.
// Do not edit: change api/template/ and run \`pnpm -C api template\`.

export interface TemplateFile {
  /** Relative to the Bower folder, \`/\`-separated. */
  path: string;
  /** UTF-8 text; empty for \`.gitkeep\` (a folder with nothing in it yet). */
  content: string;
}

/** Every file of the template, sorted by path. */
export const TEMPLATE_FILES: readonly TemplateFile[] = [
${entries.join('')}];
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = await readFile(outFile, 'utf8');
  } catch {
    // Missing counts as stale.
  }
  if (current !== output) {
    process.stderr.write('template.generated.ts is stale: run `pnpm -C api template`\n');
    process.exit(1);
  }
  process.stdout.write('template.generated.ts is current\n');
} else {
  await writeFile(outFile, output);
  process.stdout.write(`bundle-template: wrote ${entries.length} files\n`);
}
