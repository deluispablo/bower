// Turns the brand tokens (src/styles/tokens.json, from the Bower design system)
// into CSS custom properties. Dark is the reference theme; light applies when the
// system asks for it or the person picks it (data-theme on <html>).
import { readFileSync, writeFileSync } from 'node:fs';

const src = new URL('../src/styles/tokens.json', import.meta.url);
const out = new URL('../src/styles/tokens.css', import.meta.url);
const t = JSON.parse(readFileSync(src, 'utf8'));

const dark = [];
const light = [];
for (const tok of t.color.tokens) {
  const v = tok.value;
  if (typeof v === 'string') dark.push(`  --${tok.name}: ${v};`);
  else {
    dark.push(`  --${tok.name}: ${v.dark};`);
    if (v.light !== v.dark) light.push(`  --${tok.name}: ${v.light};`);
  }
}
const rest = [];
for (const fam of ['spacing', 'radius']) for (const tok of t[fam].tokens) rest.push(`  --${tok.name}: ${tok.value};`);
for (const [k, v] of Object.entries(t.type.families)) rest.push(`  --font-${k}: ${v};`);

const css = `/* Generated by scripts/tokens-to-css.mjs from tokens.json. Do not edit. */
:root {
  color-scheme: dark;
${dark.join('\n')}
${rest.join('\n')}
}
@media (prefers-color-scheme: light) {
  :root:not([data-theme='dark']) {
    color-scheme: light;
${light.map((l) => '  ' + l).join('\n')}
  }
}
:root[data-theme='light'] {
  color-scheme: light;
${light.join('\n')}
}
`;
writeFileSync(out, css);
console.log(`tokens.css: ${dark.length} colours, ${light.length} light overrides`);
